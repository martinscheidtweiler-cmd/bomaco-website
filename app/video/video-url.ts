/** Allowlist parser for shareable Vimeo and YouTube URLs, including unlisted Vimeo hashes. */
export function videoReferenceFromUrl(value: string): string | null {
  try {
    const u = new URL(value.trim());
    if (u.protocol !== "https:") return null;
    const host = u.hostname.toLowerCase().replace(/^www\./, "");
    if (host === "youtu.be" || ["youtube.com", "youtube-nocookie.com", "m.youtube.com"].includes(host)) {
      const id = host === "youtu.be" ? u.pathname.split("/")[1] : u.searchParams.get("v") || u.pathname.match(/\/(?:embed|shorts|live)\/([a-zA-Z0-9_-]{11})/)?.[1];
      return id && /^[a-zA-Z0-9_-]{11}$/.test(id) ? id : null;
    }
    if (host === "vimeo.com" || host === "player.vimeo.com") {
      const parts = u.pathname.split("/").filter(Boolean);
      // Do not mistake a showcase, channel or album ID for the video ID.
      const videoPart = parts.findIndex((p) => p === "video" || p === "videos");
      const id = videoPart >= 0 ? parts[videoPart + 1] : parts[parts.length - 1] && /^\d{5,12}$/.test(parts[parts.length - 1])
        ? parts[parts.length - 1] : parts[0];
      if (!id || !/^\d{5,12}$/.test(id)) return null;
      const next = parts[parts.indexOf(id) + 1] || "";
      const hash = u.searchParams.get("h") || (/^[a-f0-9]{6,40}$/i.test(next) ? next : "");
      if (hash && !/^[a-f0-9]{6,40}$/i.test(hash)) return null;
      return "vimeo:" + id + (hash ? ":" + hash.toLowerCase() : "");
    }
    return null;
  } catch { return null; }
}

/** Safe embed URL; accepts only verified IDs generated by videoReferenceFromUrl. */
export function videoEmbedUrl(ref: string | null | undefined): string | null {
  const value = ref || "";
  if (/^[a-zA-Z0-9_-]{11}$/.test(value))
    return "https://www.youtube-nocookie.com/embed/" + value + "?autoplay=1&rel=0";
  const match = value.match(/^vimeo:(\d{5,12})(?::([a-f0-9]{6,40}))?$/i);
  if (!match) return null;
  return "https://player.vimeo.com/video/" + match[1] + "?" +
    (match[2] ? "h=" + match[2].toLowerCase() + "&" : "") +
    "autoplay=1&dnt=1&title=0&byline=0&portrait=0";
}
